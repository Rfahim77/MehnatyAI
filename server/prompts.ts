export function getRewriteBulletsPrompt(
  resumeJson: ResumeJson,
  targetJob: string,
  tone: string
): string {
  const experienceText = resumeJson.experience
    .map(exp => `${exp.title} في ${exp.company}: ${exp.bullets.join("; ")}`)
    .join("\n");

  return `أعد كتابة نقاط الخبرة لتناسب "الوظيفة المستهدفة: ${targetJob}" وبالنبرة: ${tone}.

الخبرات الحالية:
${experienceText}

القالب: [فعل قوي] + [مهمة/سياق] + [أداة/مهارة] + [نتيجة رقمية].
القيود: ≤ 20 كلمة لكل نقطة، عربية فصيحة، بلا مبالغة.
عند غياب الأرقام، أضف "(أضف رقماً تقريبياً)" بدلاً من اختراع رقم.

أخرجها كأقسام Markdown مرتبة حسب الخبرة (استخدم ### للعناوين وقوائم نقطية).`;
}

